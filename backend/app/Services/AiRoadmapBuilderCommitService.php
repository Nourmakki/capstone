<?php

namespace App\Services;

use App\Models\Edge;
use App\Models\Node;
use App\Models\Roadmap;
use App\Models\RoadmapBuilderRun;
use App\Models\RoadmapVersion;
use App\Models\VersionEdge;
use App\Models\VersionNode;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\ValidationException;

/**
 * Write a finished roadmap-builder run into our tables.
 *
 * Her package is a whole subject at once, and it maps onto the three levels
 * we already have:
 *
 *   roadmap_topic                     -> a top-level roadmap
 *     GeneratedPathRoadmapModel       -> a path beneath it, with a version
 *       StandardRoadmapNodeModel      -> a module
 *       ChoiceRoadmapNodeModel        -> a module offering choices
 *         RoadmapChoiceModel          -> a choice
 *           separate_roadmap: true    -> a level-3 roadmap, from child_roadmaps
 *
 * Everything lands unapproved and unpublished. The AI proposes a subject; a
 * material manager decides whether students ever see it, which is the same
 * line every other AI path draws.
 *
 * The structure only. No learning material is written and none is asked for -
 * a subject is far too many modules to generate in one go, and which of them
 * are worth filling in is the manager's call, module by module, on the
 * Learning Material page.
 *
 * One transaction: a half-written subject is worse than none, because the
 * pieces look real and nobody knows which are missing.
 */
class AiRoadmapBuilderCommitService
{
    public function __construct(private NodeChoiceRules $choiceRules)
    {
    }

    /**
     * @param array $payload her RoadmapBuilderWorkflowResponse, decoded
     *
     * @throws ValidationException
     */
    public function commit(RoadmapBuilderRun $run, array $payload): Roadmap
    {
        $packages = $payload['data']['approved_roadmap_packages'] ?? [];

        if ($packages === []) {
            throw ValidationException::withMessages([
                'commit' => 'This run produced no approved roadmaps, so there is nothing to commit.',
            ]);
        }

        $subject = DB::transaction(function () use ($run, $packages) {
            $subject = $this->subjectFor($run);

            foreach ($packages as $package) {
                $this->commitPath($subject, $package);
            }

            $run->update([
                'status'               => 'committed',
                'committed_roadmap_id' => $subject->id,
                'committed_at'         => now(),
            ]);

            return $subject;
        });

        // No learning runs are started here, deliberately.
        //
        // This used to queue one per module, so approving a build put the
        // whole subject into generation at once. A subject is sixty-odd
        // modules and each run is a multi-minute call to her service, so that
        // buried the machine and took the site down with it - and it spent
        // the day's API quota on modules nobody had decided to fill in yet.
        //
        // The modules arrive marked coming-soon instead, which is what makes
        // them publishable while empty. They are listed on the Learning
        // Material page as awaiting material, and a manager generates them
        // one at a time, in the order they care about.
        return $subject;
    }

    /**
     * The top-level roadmap the paths hang from.
     *
     * Reused when one of that name already exists, so running the builder for
     * a subject we already teach adds paths to it rather than creating a
     * second "Web Development" beside the first.
     */
    private function subjectFor(RoadmapBuilderRun $run): Roadmap
    {
        $existing = Roadmap::whereRaw('LOWER(title) = ?', [mb_strtolower(trim($run->topic))])
            ->topLevel()
            ->first();

        if ($existing) {
            return $existing;
        }

        return Roadmap::create([
            'title'         => $this->titleCase($run->topic),
            'description'   => 'Generated by the AI system.',
            'review_status' => 'pending',
        ]);
    }

    /** One GeneratedPathRoadmapModel: a path, its modules and its children. */
    private function commitPath(Roadmap $subject, array $package): void
    {
        $result = $package['roadmap_result'] ?? [];

        $path = Roadmap::create([
            'title'             => $package['path_title'] ?? ($result['title'] ?? 'Untitled path'),
            'description'       => $result['description'] ?? '',
            'review_status'     => 'pending',
            'parent_roadmap_id' => $subject->id,
        ]);

        $version = RoadmapVersion::create([
            'roadmap_id'     => $path->id,
            'version_number' => '1',
            // Draft and pending: the manager publishes, and the publish gate
            // still asks for material on every module first.
            'status'         => 'Draft',
            'review_status'  => 'pending',
            // But visible meanwhile. Students see the roadmap's shape marked
            // coming soon, with every module locked, rather than nothing at
            // all while its material is being written.
            'announced'      => true,
        ]);

        // Her node ids are local to the payload, so keep a map from hers to
        // the rows we create - prerequisites and child roadmaps both refer
        // back to them.
        $nodeIdMap    = [];
        $versionNodes = [];

        foreach ($result['nodes'] ?? [] as $node) {
            $created = $this->commitNode($version, $node);

            $nodeIdMap[$node['node_id']]    = $created->node_id;
            $versionNodes[$node['node_id']] = $created;
        }

        $this->commitEdges($version, $result['nodes'] ?? [], $nodeIdMap);

        // Choices that carry their own roadmap, matched to their choice by
        // (parent_node_id, choice_id) exactly as she pairs them.
        foreach ($package['child_roadmaps'] ?? [] as $child) {
            $this->commitChildRoadmap($path, $versionNodes, $child);
        }
    }

    /** A module, and its choices if it has any. */
    private function commitNode(RoadmapVersion $version, array $node): VersionNode
    {
        // Announced, not yet teachable - the same mark the trends commit puts
        // on the modules it invents.
        //
        // Without it a whole new subject could not be published at all: the
        // gate asks every module for a tutorial, quiz and project, and a
        // roadmap the AI has just written has none. Sixty-odd modules would
        // each have needed a learning run before a student could see any of
        // it. Marked coming-soon they are exempt from the gate, so the
        // structure goes live locked, and each module opens as its material
        // is approved - which is exactly what the trends path already does.
        $created = VersionNode::create([
            'roadmap_version_id' => $version->id,
            'node_id'            => $this->makeNode($node)->id,
            // Her `order` is the sequence; we group by it so a generated
            // roadmap arrives with stages rather than as a flat list.
            'stage'              => $node['order'] ?? null,
            'coming_soon'        => true,
        ]);

        foreach ($node['choices'] ?? [] as $choice) {
            VersionNode::create([
                'roadmap_version_id'     => $version->id,
                'node_id'                => $this->makeNode($choice)->id,
                'parent_version_node_id' => $created->id,
                'is_recommended'         => (bool) ($choice['recommended'] ?? false),
                'recommendation_reason'  => $choice['recommendation_reason'] ?? null,
                'coming_soon'            => true,
            ]);
        }

        // Her own validators already enforce this, but the manual editor can
        // reach the same rows - so it is checked on the way in either way.
        if (! empty($node['choices'])) {
            $this->choiceRules->assertValid($created->fresh());
        }

        return $created;
    }

    /**
     * The prerequisite links. Her prerequisite_node_ids are "what must come
     * before this", which is the direction our edges already run.
     */
    private function commitEdges(RoadmapVersion $version, array $nodes, array $nodeIdMap): void
    {
        foreach ($nodes as $node) {
            foreach ($node['prerequisite_node_ids'] ?? [] as $before) {
                // A prerequisite naming a node she did not send would create
                // an edge to nothing; skip it rather than fail the subject.
                if (! isset($nodeIdMap[$before], $nodeIdMap[$node['node_id']])) {
                    continue;
                }

                $edge = Edge::firstOrCreate([
                    'from_node_id' => $nodeIdMap[$before],
                    'to_node_id'   => $nodeIdMap[$node['node_id']],
                ]);

                VersionEdge::create([
                    'roadmap_version_id' => $version->id,
                    'edge_id'            => $edge->id,
                ]);
            }
        }
    }

    /**
     * A choice big enough for a roadmap of its own - her separate_roadmap.
     *
     * The level-3 roadmap is created under the path, and the choice that
     * asked for it is pointed at it.
     */
    private function commitChildRoadmap(Roadmap $path, array $versionNodes, array $child): void
    {
        $parent = $versionNodes[$child['parent_node_id']] ?? null;

        if (! $parent) {
            return;
        }

        $choice = VersionNode::where('parent_version_node_id', $parent->id)
            ->whereHas('node', fn ($q) => $q->whereRaw(
                'LOWER(title) = ?',
                [mb_strtolower(trim($child['choice_title'] ?? ''))]
            ))
            ->first();

        if (! $choice) {
            return;
        }

        $result = $child['roadmap_result'] ?? [];

        $childRoadmap = Roadmap::create([
            'title'             => $child['choice_title'],
            'description'       => $result['description'] ?? '',
            'review_status'     => 'pending',
            'parent_roadmap_id' => $path->id,
        ]);

        $version = RoadmapVersion::create([
            'roadmap_id'     => $childRoadmap->id,
            'version_number' => '1',
            'status'         => 'Draft',
            'review_status'  => 'pending',
            // Announced like its parent: a choice that opens its own roadmap
            // would otherwise lead to an empty page.
            'announced'      => true,
        ]);

        $nodeIdMap = [];

        foreach ($result['nodes'] ?? [] as $node) {
            // Her GeneratedChildRoadmap forbids separate_roadmap inside a
            // child, so these are plain modules - three levels is the limit.
            $created = $this->commitNode($version, $node);
            $nodeIdMap[$node['node_id']] = $created->node_id;
        }

        $this->commitEdges($version, $result['nodes'] ?? [], $nodeIdMap);

        $choice->update(['links_to_roadmap_id' => $childRoadmap->id]);
    }

    /**
     * Her nodes and choices both carry a title and description, and our Node
     * needs a difficulty she does not send - so it is inferred from position
     * rather than invented per node.
     */
    private function makeNode(array $source): Node
    {
        return Node::create([
            'title'       => $source['title'] ?? 'Untitled',
            'description' => $source['description'] ?? '',
            'difficulty'  => match (true) {
                ($source['order'] ?? 1) <= 1 => 'beginner',
                ($source['order'] ?? 1) <= 3 => 'intermediate',
                default                      => 'advanced',
            },
            'status'      => 'approved',
        ]);
    }

    private function titleCase(string $topic): string
    {
        return mb_convert_case(trim($topic), MB_CASE_TITLE, 'UTF-8');
    }
}
